import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const root='offline';const html=fs.readFileSync(path.join(root,'index.html'),'utf8');const css=fs.readFileSync(path.join(root,'game.css'),'utf8');const js=fs.readFileSync(path.join(root,'game.js'),'utf8');
assert(!html.includes('type="module"'),'must use classic script for file://');
assert(!/<(?:script|link)[^>]+(?:src|href)="https?:/i.test(html),'no external code or styles');
new vm.Script(js,{filename:'game.js'});
assert(!/\bimport\(/.test(js),'no split chunks');
assert(!/url\(["']?https?:/.test(css),'no external image or font dependency');
for(const file of ['game.js','game.css','favicon.svg','启动游戏.command','启动游戏.bat','启动游戏.sh'])assert(fs.existsSync(path.join(root,file)),file);
const manifest=JSON.parse(fs.readFileSync('public/media/sources.json','utf8'));for(const asset of manifest.assets)assert(fs.existsSync(path.join(root,'media',asset.filename)),asset.filename);
assert.equal(manifest.assets.filter(a=>a.kind==='character_artwork').length,6);
assert(fs.statSync(path.join(root,'启动游戏.command')).mode&0o111);
console.log('PASS offline package: classic IIFE, no external dependencies, 6 official artworks, all asset references and launchers present.');
